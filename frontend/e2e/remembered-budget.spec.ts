import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.route('https://ddragon.leagueoflegends.com/**', (route) => route.abort())
  await page.emulateMedia({ reducedMotion: 'reduce' })
})

test('il budget scelto si riusa tra riepilogo e piano dopo refresh completo @smoke', async ({ page }, testInfo) => {
  const writes: string[] = []
  page.on('request', (request) => { if (request.method() !== 'GET') writes.push(request.url()) })
  await page.goto('/app/overview')
  await page.reload()
  const overviewBudget = page.getByRole('spinbutton', { name: 'Partite del piano' })
  await expect(overviewBudget).toHaveValue('400')
  await overviewBudget.fill('120')
  await overviewBudget.press('Enter')
  await expect(page.locator('.overview-plan__allocation')).toHaveText('120partite distribuite')

  await page.goto('/app/fit?section=tournament')
  await page.reload()
  const planBudget = page.getByRole('spinbutton', { name: 'Budget partite' })
  await expect(planBudget).toHaveValue('120')
  await planBudget.fill('80')
  await planBudget.press('Enter')
  await expect(page.getByRole('heading', { name: 'Piano da 80 partite', exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: 'Ruolo', exact: true }).selectOption('MIDDLE')
  await page.getByRole('combobox', { name: 'Modalità', exact: true }).selectOption('420')

  await page.goto('/app/overview')
  await page.reload()
  await expect(overviewBudget).toHaveValue('80')
  await expect(page.locator('.overview-plan__allocation')).toHaveText('80partite distribuite')
  // The shared budget does not replace the independent analysis context.
  await expect(page.getByRole('combobox', { name: 'Ruolo', exact: true })).toHaveValue('')
  await expect(page.getByRole('combobox', { name: 'Modalità', exact: true })).toHaveValue('')
  await expect(page.getByRole('link', { name: 'Apri il piano', exact: true })).toHaveAttribute('href', /budget=80/)
  await page.getByRole('combobox', { name: 'Modalità', exact: true }).selectOption('440')
  await expect(overviewBudget).toHaveValue('80')
  await expect(page.locator('.overview-plan__allocation')).toHaveText('80partite distribuite')
  await page.reload()
  await expect(overviewBudget).toHaveValue('80')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('remembered-budget.png'), fullPage: true })
  expect(writes).toEqual([])
})

test('i link espliciti mantengono il proprio budget senza sostituire la preferenza @smoke', async ({ page }) => {
  await page.goto('/app/overview')
  await page.reload()
  const overviewBudget = page.getByRole('spinbutton', { name: 'Partite del piano' })
  await overviewBudget.fill('80')
  await overviewBudget.press('Enter')
  await expect(page.locator('.overview-plan__allocation')).toHaveText('80partite distribuite')

  await page.goto('/app/overview?budget=200&queue=440')
  await page.reload()
  await expect(overviewBudget).toHaveValue('200')
  await expect(page.locator('.overview-plan__allocation')).toHaveText('200partite distribuite')
  await page.goto('/app/fit?section=tournament&budget=200')
  const planBudget = page.getByRole('spinbutton', { name: 'Budget partite' })
  await expect(planBudget).toHaveValue('200')
  await planBudget.focus()
  await planBudget.press('Tab')
  await page.goto('/app/fit?section=tournament&queue=440')
  await expect(page.getByRole('spinbutton', { name: 'Budget partite' })).toHaveValue('400')
  await page.goto('/app/overview?queue=440')
  await expect(overviewBudget).toHaveValue('400')
  await page.goto('/app/overview')
  await page.reload()
  await expect(overviewBudget).toHaveValue('80')
  await expect(page.locator('.overview-plan__allocation')).toHaveText('80partite distribuite')
})
