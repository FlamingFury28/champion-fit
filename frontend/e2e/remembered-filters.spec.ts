import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.route('https://ddragon.leagueoflegends.com/**', (route) => route.abort())
  await page.emulateMedia({ reducedMotion: 'reduce' })
})

test('ritorno allo storico: ripristina i filtri, rispetta i link espliciti e ricorda il reset @smoke', async ({ page }, testInfo) => {
  const writes: string[] = []
  page.on('request', (request) => {
    if (request.method() !== 'GET') writes.push(request.url())
  })
  await page.goto('/app/matches')
  await expect(page.locator('#main-content .skeleton')).toHaveCount(0)
  await expect(page.getByRole('combobox', { name: 'Campione', exact: true }).locator('option[value="Ahri"]')).toBeAttached()
  await page.reload()
  const filters = page.getByRole('group', { name: 'Filtri delle partite' })
  const select = (name: string) => filters.getByRole('combobox', { name, exact: true })
  await expect(select('Campione').locator('option[value="Ahri"]')).toBeAttached()
  await select('Campione').selectOption('Ahri')
  await select('Ruolo').selectOption('MIDDLE')
  await select('Modalità').selectOption('420')
  await select('Periodo').selectOption('90')
  await expect(page.locator('.filter-count')).toHaveText('3 di 3 partite')
  await page.goto('/app/profile')
  await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
  await page.goto('/app/matches')
  await expect(select('Campione')).toHaveValue('Ahri')
  await expect(page.locator('.filter-count')).toHaveText('3 di 3 partite')
  await page.reload()
  await expect(select('Ruolo')).toHaveValue('MIDDLE')
  await expect(select('Modalità')).toHaveValue('420')
  await expect(select('Periodo')).toHaveValue('90')
  await expect(page.locator('.filter-count')).toHaveText('3 di 3 partite')
  await page.evaluate(() => document.fonts.ready)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('remembered-history.png'), fullPage: true })
  await page.goto('/app/matches?queue=440')
  await expect(select('Campione')).toHaveValue('')
  await expect(select('Ruolo')).toHaveValue('ALL')
  await expect(select('Periodo')).toHaveValue('all')
  await expect(page.locator('.filter-count')).toHaveText('2 di 2 partite')
  await page.goto('/app/matches')
  await expect(select('Campione')).toHaveValue('Ahri')
  await page.getByRole('button', { name: 'Azzera filtri' }).click()
  await expect(page.locator('.filter-count')).toHaveText('6 di 6 partite')
  await page.reload()
  await expect(select('Campione')).toHaveValue('')
  await expect(page.locator('.filter-count')).toHaveText('6 di 6 partite')
  expect(writes).toEqual([])
})

test('piano: budget e contesto ritrovati senza nuove selezioni e senza scritture al server @smoke', async ({ page }, testInfo) => {
  const writes: string[] = []
  page.on('request', (request) => {
    if (request.method() !== 'GET') writes.push(request.url())
  })
  await page.goto('/app/fit?section=tournament')
  await expect(page.getByRole('heading', { name: 'Piano da 400 partite', exact: true })).toBeVisible()
  await expect(page.locator('#main-content .skeleton')).toHaveCount(0)
  await page.reload()
  const budget = page.getByRole('spinbutton', { name: 'Budget partite' })
  const role = page.getByRole('combobox', { name: 'Ruolo', exact: true })
  const queue = page.getByRole('combobox', { name: 'Modalità', exact: true })
  const period = page.getByRole('combobox', { name: 'Periodo', exact: true })
  await budget.fill('80')
  await budget.press('Enter')
  await role.selectOption('MIDDLE')
  await queue.selectOption('420')
  await period.selectOption('90')
  await expect(page.getByRole('region', { name: 'Riepilogo del piano' })).toBeVisible()
  await page.goto('/app/profile')
  await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
  await page.goto('/app/fit?section=tournament')
  await expect(budget).toHaveValue('80')
  await expect(role).toHaveValue('MIDDLE')
  await expect(queue).toHaveValue('420')
  await expect(period).toHaveValue('90')
  await expect(page.getByRole('heading', { name: 'Piano da 80 partite', exact: true })).toBeVisible()
  await page.reload()
  await expect(budget).toHaveValue('80')
  await expect(page.getByRole('region', { name: 'Riepilogo del piano' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.evaluate(() => document.fonts.ready)
  await page.screenshot({ path: testInfo.outputPath('remembered-plan.png'), fullPage: true })
  await page.goto('/app/fit?section=tournament&budget=120')
  await expect(budget).toHaveValue('120')
  await expect(role).toHaveValue('')
  await expect(queue).toHaveValue('')
  await expect(period).toHaveValue('')
  await page.goto('/app/fit?section=tournament')
  await expect(budget).toHaveValue('80')
  await expect(role).toHaveValue('MIDDLE')
  expect(writes).toEqual([])
})
