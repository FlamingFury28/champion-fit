import { describe, expect, it } from 'vitest'
import { normalizeDateFilter } from './iso-calendar'

describe('date dei filtri compatibili con date.fromisoformat', () => {
  it.each([
    ['2026-01-01', '2026-01-01'],
    ['20260101', '2026-01-01'],
    ['2026-W01-4', '2026-01-01'],
    ['2026W014', '2026-01-01'],
    ['2026-W01', '2025-12-29'],
    ['2026W01', '2025-12-29'],
    ['2020-W53-7', '2021-01-03'],
    ['2026W537', '2027-01-03'],
    ['2000-02-29', '2000-02-29'],
    ['00960229', '0096-02-29'],
    ['0001-01-01', '0001-01-01'],
    ['0001-W01', '0001-01-01'],
    ['99991231', '9999-12-31'],
    ['9999W525', '9999-12-31'],
    [' \t20260101\r\n', '2026-01-01'],
    ['\u00852026-W01-4\u0085', '2026-01-01'],
    ['\u001c\u001d20260101\u001e\u001f', '2026-01-01'],
    ['\u00a0\u1680\u20002026W014\u202f\u205f\u3000', '2026-01-01'],
  ])('normalizza %j in %s', (input, expected) => {
    expect(normalizeDateFilter(input)).toBe(expected)
  })

  it.each([
    undefined, null, '', ' ', 'invalid', '2026-02-30', '20260229', '1900-02-29',
    '0000-01-01', '10000-01-01', '2026-00-01', '2026-13-01', '2026-01-00',
    '2021-W53-1', '2026-W00-1', '2026-W54-1', '2026-W01-0', '2026-W01-8',
    '9999-W52-6', '9999W527', '2026-W014', '2026W01-4', '2026-w01-4',
    '2026-W1-1', '2026-W01-01', '2026-1-1', '2026-001', '2026-01',
    '2026-01-01T00:00:00Z', '+2026-01-01', '\ufeff2026-01-01', '20260101\ufeff',
    '２０２６０１０１', '2026-01-01\u200b',
  ])('ignora %j senza rollover o formati aggiuntivi', (input) => {
    expect(normalizeDateFilter(input)).toBe('')
  })
})
